// Direct backend integration - bypasses Edge Function
import { NextRequest, NextResponse } from 'next/server'
import { auth } from '@clerk/nextjs/server'
import { createClient } from '@supabase/supabase-js'

function normalizeBackendBaseUrl(raw: string) {
  if (!raw) {
    throw new Error('BACKEND_URL is missing')
  }
  const trimmed = raw.trim()
  const withScheme = trimmed.startsWith('http://') || trimmed.startsWith('https://')
    ? trimmed
    : `https://${trimmed}`
  return withScheme.replace(/\/api\/v1\/?$/, '')
}

const BACKEND_URL = normalizeBackendBaseUrl(
  process.env.BACKEND_URL
    || process.env.NEXT_PUBLIC_BACKEND_URL
    || 'http://backend:8000'
)
const BACKEND_API_KEY = process.env.BACKEND_API_KEY || 'test-key'
const SUPABASE_URL = process.env.SUPABASE_URL || process.env.NEXT_PUBLIC_SUPABASE_URL
const SUPABASE_SERVICE_KEY = process.env.SUPABASE_SERVICE_KEY || process.env.SUPABASE_SERVICE_ROLE_KEY

function escapePdfText(value: unknown) {
  return String(value ?? '')
    .replace(/\\/g, '\\\\')
    .replace(/\(/g, '\\(')
    .replace(/\)/g, '\\)')
    .replace(/\r?\n/g, ' ')
}

function createDemoPdfBuffer(analysis: any, reportType: string, reportNumber: string) {
  const rows = [
    'MIDAS Medical Report',
    `Report: ${reportNumber}`,
    `Type: ${reportType}`,
    `Diagnosis: ${analysis.diagnosis || 'Analysis result'}`,
    `Risk level: ${analysis.risk_level || 'Unknown'}`,
    `Confidence: ${Number(analysis.confidence || 0).toFixed(1)}%`,
    `Generated: ${new Date().toLocaleString()}`,
    '',
    'Demo fallback: generated by the Next.js app because the Python PDF backend is unavailable.',
    'This report is educational information only and is not a medical diagnosis.',
    'Please consult a qualified dermatologist for proper evaluation and treatment.',
  ]

  const textCommands = rows
    .map((line, index) => `BT /F1 12 Tf 50 ${760 - index * 22} Td (${escapePdfText(line)}) Tj ET`)
    .join('\n')

  const objects = [
    '1 0 obj << /Type /Catalog /Pages 2 0 R >> endobj',
    '2 0 obj << /Type /Pages /Kids [3 0 R] /Count 1 >> endobj',
    '3 0 obj << /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >> endobj',
    '4 0 obj << /Type /Font /Subtype /Type1 /BaseFont /Helvetica >> endobj',
    `5 0 obj << /Length ${Buffer.byteLength(textCommands)} >> stream\n${textCommands}\nendstream endobj`,
  ]

  let pdf = '%PDF-1.4\n'
  const offsets = [0]
  for (const object of objects) {
    offsets.push(Buffer.byteLength(pdf))
    pdf += `${object}\n`
  }
  const xrefOffset = Buffer.byteLength(pdf)
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`
  for (let i = 1; i < offsets.length; i += 1) {
    pdf += `${String(offsets[i]).padStart(10, '0')} 00000 n \n`
  }
  pdf += `trailer << /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF\n`
  return Buffer.from(pdf)
}

export async function POST(request: NextRequest) {
  try {
    // 1. Authenticate with Clerk
    const { userId } = await auth()
    if (!userId) {
      return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })
    }

    if (!SUPABASE_URL || !SUPABASE_SERVICE_KEY) {
      return NextResponse.json(
        { error: 'Supabase credentials not configured' },
        { status: 500 }
      )
    }

    // 2. Parse request
    const body = await request.json()
    const { analysis_id, config } = body
    const reportType = config?.reportType || 'diagnostic_summary'

    if (!analysis_id) {
      return NextResponse.json({ error: 'analysis_id is required' }, { status: 400 })
    }

    // 3. Create Supabase client (server-side with service key)
    const supabase = createClient(SUPABASE_URL, SUPABASE_SERVICE_KEY)

    // 4. Fetch analysis from Supabase
    const { data: analysis, error: analysisError } = await supabase
      .from('medical_analyses')
      .select('*')
      .eq('id', analysis_id)
      .single()

    if (analysisError || !analysis) {
      return NextResponse.json(
        { error: 'Analysis not found', details: 'This analysis does not exist in the database' },
        { status: 404 }
      )
    }

    // 5. Check authorization (user must own the analysis)
    if (analysis.user_id !== userId) {
      return NextResponse.json({ error: 'Forbidden' }, { status: 403 })
    }

    // 6. Generate report number
    const { data: reportNumber } = await supabase.rpc('generate_report_number')
    const dateStamp = new Date().toISOString().slice(0, 10).replace(/-/g, '')
    const randomToken = Math.random().toString(36).slice(2, 8).toUpperCase()
    const fallbackReportNumber = `MIDAS-REP-${dateStamp}-${randomToken}`
    const normalizedReportNumber = reportNumber || fallbackReportNumber

    // 7. Create report record
    const { data: reportRecord, error: insertError } = await supabase
      .from('generated_reports')
      .insert({
        user_id: userId,
        analysis_id: analysis.id,
        report_type: reportType,
        report_number: normalizedReportNumber,
        generation_status: 'generating',
        report_config: config
      })
      .select()
      .single()

    if (insertError || !reportRecord) {
      console.error('Failed to create report record:', insertError)
      return NextResponse.json(
        {
          error: 'Failed to create report',
          details: insertError?.message || 'Unknown insert error'
        },
        { status: 500 }
      )
    }

    // 8. Call backend to generate PDF; fall back locally for demo stability.
    let backendResponse: Response | null = null
    try {
      backendResponse = await fetch(new URL('/api/v1/reports/generate', BACKEND_URL), {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'Authorization': `Bearer ${BACKEND_API_KEY}`
        },
        body: JSON.stringify({
          report_id: reportRecord.id,
          analysis_id: analysis.id,
          report_type: reportType,
          user_id: userId,
          config: config
        })
      })
    } catch (backendError) {
      console.error('Backend report service unavailable, using demo PDF fallback:', backendError)
    }

    if (backendResponse && !backendResponse.ok) {
      const errorText = await backendResponse.text()
      console.error('Backend error:', errorText)
      backendResponse = null
    }

    // 9. Get PDF from backend
    const pdfBuffer = backendResponse
      ? Buffer.from(await (await backendResponse.blob()).arrayBuffer())
      : createDemoPdfBuffer(analysis, reportType, normalizedReportNumber)

    // 10. Upload PDF to Supabase Storage
    const storagePath = `${userId}/reports/${reportRecord.id}_${reportType}.pdf`

    const { error: uploadError } = await supabase.storage
      .from('report_storage')
      .upload(storagePath, pdfBuffer, {
        contentType: 'application/pdf',
        upsert: true
      })

    if (uploadError) {
      console.error('Storage upload error:', uploadError)
      await supabase
        .from('generated_reports')
        .update({ generation_status: 'failed', error_message: uploadError.message })
        .eq('id', reportRecord.id)

      return NextResponse.json({ error: 'Failed to upload PDF' }, { status: 500 })
    }

    // 11. Generate signed URL for preview
    const { data: signedUrlData } = await supabase.storage
      .from('report_storage')
      .createSignedUrl(storagePath, 3600) // 1 hour

    // 12. Update report record
    await supabase
      .from('generated_reports')
      .update({
        storage_path: storagePath,
        generation_status: 'completed',
        generated_at: new Date().toISOString()
      })
      .eq('id', reportRecord.id)

    // 13. Return success
    return NextResponse.json({
      success: true,
      report_id: reportRecord.id,
      report_number: reportRecord.report_number,
      preview_url: signedUrlData?.signedUrl,
      report_type: reportType,
      generated_at: new Date().toISOString(),
      message: 'Report generated successfully'
    })

  } catch (error) {
    console.error('API route error:', error)
    return NextResponse.json(
      { error: 'Internal server error', details: error instanceof Error ? error.message : 'Unknown error' },
      { status: 500 }
    )
  }
}
